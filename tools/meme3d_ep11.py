def words(who: str | None = None) -> list[dict]:
    """Слова (для субтитров и рта): {w — подпись, say — произношение, t0, t1, who}."""
    out = [{"who": w, "w": cap, "say": say, "t0": a, "t1": b} for w, cap, say, a, b in WORDS]
    return [x for x in out if who is None or x["who"] == who]



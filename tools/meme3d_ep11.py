def on_grid(t: float) -> float:
    """Шаг сетки 1/15 с, усечённый вниз до 3 знаков (как meme3d_ep9_anim.on_grid): 10.667 > 32/3 — кадр 320 остался бы
    в прошлом плане, склейка опоздала бы на кадр."""
    return math.floor(round(t * 15) / 15 * 1000) / 1000


def _shots() -> list[tuple[float, float, str]]:
    a = [(on_grid(t0), n) for t0, n in SHOTS_RAW]
    return [(t0, a[i + 1][0] if i + 1 < len(a) else DURATION, n) for i, (t0, n) in enumerate(a)]


